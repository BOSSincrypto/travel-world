const slugify = (value: string) => value.toLocaleLowerCase('ru-RU').replace(/[ё]/g, 'е').replace(/[^a-zа-я0-9]+/gi, '-')

export const COUNTRIES: Country[] = Object.entries(groups).flatMap(([region, names]) => names.map((name, index) => {
  const id = slugify(name)
  const coordinates = featuredCoordinates[id]
  return {
    id,
    name,
    region: region as Region,
    code: `${region.slice(0, 2)}-${index + 1}`,
    mapX: coordinates?.[0],
    mapY: coordinates?.[1],
    mapLabel: coordinates?.[2],
  }
}))

export const COUNTRY_COUNT = 195

export const getCountry = (id: string) => COUNTRIES.find((country) => country.id === id)

export const featuredCountries = COUNTRIES.filter((country) => country.mapX !== undefined)

export const regionCounts = Object.entries(groups).map(([name, countries]) => ({
  name: name as Region,
  count: countries.length,
}))
